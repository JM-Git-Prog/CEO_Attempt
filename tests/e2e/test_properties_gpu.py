class TestProperty16ArtifactEndpointCorrectness:
    """**Validates: Requirements 19.1, 19.3, 19.4**

    For any completed stage artifact served via API, the response SHALL have
    HTTP 200, correct Content-Type (image/png or image/jpeg), file size > 1KB,
    and Cache-Control: no-store header.
    """

    @given(
        body_size=st.integers(min_value=1025, max_value=100_000_000),
        content_type=st.sampled_from(["image/png", "image/jpeg"]),
    )
    @_SETTINGS
    def test_correct_response_passes_all_checks(
        self, body_size: int, content_type: str
    ) -> None:
        """A fully correct artifact response passes validation.

        **Validates: Requirements 19.1, 19.3, 19.4**
        """
        response = ArtifactResponse(
            status_code=200,
            content_type=content_type,
            body_size=body_size,
            cache_control="no-store",
        )
        valid, failures = validate_artifact_response(response)
        assert valid is True, f"Correct response should pass: {failures}"
        assert failures == []

    @given(
        status_code=st.sampled_from([201, 301, 400, 404, 500, 502, 503]),
    )
    @_SETTINGS
    def test_non_200_status_fails(self, status_code: int) -> None:
        """Any status code other than 200 fails the check.

        **Validates: Requirements 19.1**
        """
        response = ArtifactResponse(
            status_code=status_code,
            content_type="image/png",
            body_size=2048,
            cache_control="no-store",
        )
        valid, failures = validate_artifact_response(response)
        assert valid is False
        assert any("200" in f for f in failures)

    @given(
        content_type=st.sampled_from([
            "text/html", "application/json", "application/octet-stream",
            "image/webp", "image/gif", "text/plain",
        ]),
    )
    @_SETTINGS
    def test_wrong_content_type_fails(self, content_type: str) -> None:
        """Content-Type other than image/png or image/jpeg fails.

        **Validates: Requirements 19.1**
        """
        response = ArtifactResponse(
            status_code=200,
            content_type=content_type,
            body_size=2048,
            cache_control="no-store",
        )
        valid, failures = validate_artifact_response(response)
        assert valid is False
        assert any("Content-Type" in f for f in failures)

    @given(
        body_size=st.integers(min_value=0, max_value=1024),
    )
    @_SETTINGS
    def test_body_size_leq_1kb_fails(self, body_size: int) -> None:
        """Body size <= 1KB (1024 bytes) fails the size check.

        **Validates: Requirements 19.3**
        """
        response = ArtifactResponse(
            status_code=200,
            content_type="image/png",
            body_size=body_size,
            cache_control="no-store",
        )
        valid, failures = validate_artifact_response(response)
        assert valid is False
        assert any("size" in f.lower() or "1024" in f for f in failures)

    @given(
        cache_control=st.one_of(
            st.none(),
            st.sampled_from([
                "no-cache",
                "max-age=3600",
                "public, max-age=86400",
                "private",
            ]),
        ),
    )
    @_SETTINGS
    def test_missing_no_store_header_fails(
        self, cache_control: Optional[str]
    ) -> None:
        """Cache-Control without 'no-store' fails the header check.

        **Validates: Requirements 19.4**
        """
        response = ArtifactResponse(
            status_code=200,
            content_type="image/png",
            body_size=2048,
            cache_control=cache_control,
        )
        valid, failures = validate_artifact_response(response)
        assert valid is False
        assert any("no-store" in f for f in failures)

    @given(
        cache_control=st.sampled_from([
            "no-store",
            "no-store, no-cache",
            "private, no-store",
            "no-store, max-age=0",
        ]),
    )
    @_SETTINGS
    def test_cache_control_containing_no_store_passes(
        self, cache_control: str
    ) -> None:
        """Cache-Control containing 'no-store' (even with other directives) passes.

        **Validates: Requirements 19.4**
        """
        response = ArtifactResponse(
            status_code=200,
            content_type="image/png",
            body_size=2048,
            cache_control=cache_control,
        )
        valid, failures = validate_artifact_response(response)
        assert valid is True, f"no-store present but failed: {failures}"

    @given(
        status_code=_status_code_st,
        content_type=_content_type_st,
        body_size=_body_size_st,
        cache_control=_cache_control_st,
    )
    @_SETTINGS
    def test_validation_reports_all_failures(
        self,
        status_code: int,
        content_type: str,
        body_size: int,
        cache_control: Optional[str],
    ) -> None:
        """Validation reports ALL failures, not just the first one found.

        **Validates: Requirements 19.1, 19.3, 19.4**
        """
        response = ArtifactResponse(
            status_code=status_code,
            content_type=content_type,
            body_size=body_size,
            cache_control=cache_control,
        )
        valid, failures = validate_artifact_response(response)

        # Count how many individual checks fail
        expected_failure_count = 0
        if status_code != 200:
            expected_failure_count += 1
        if content_type not in VALID_CONTENT_TYPES:
            expected_failure_count += 1
        if body_size <= MIN_ARTIFACT_SIZE:
            expected_failure_count += 1
        if cache_control is None or "no-store" not in cache_control:
            expected_failure_count += 1

        # valid == True iff no failures
        assert valid == (expected_failure_count == 0), (
            f"valid={valid} but expected_failure_count={expected_failure_count}"
        )
        # All failures should be reported
        assert len(failures) == expected_failure_count, (
            f"Expected {expected_failure_count} failure(s), got {len(failures)}: "
            f"{failures}"
        )
