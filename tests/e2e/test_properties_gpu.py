from dataclasses import dataclass
from typing import Optional

from hypothesis import given, settings, assume, HealthCheck
from hypothesis import strategies as st

# Use a reasonable max_examples for CI performance
_SETTINGS = settings(deadline=None, max_examples=100, suppress_health_check=[HealthCheck.too_slow])


# ---------------------------------------------------------------------------
# Domain models for property testing (no external dependencies needed)
# ---------------------------------------------------------------------------


@dataclass
class HealthCheckResult:
    """Result of a health check with retry logic."""

    success: bool
    attempt_count: int
    total_elapsed_s: float
    last_error: Optional[str]


@dataclass
class ArtifactResponse:
    """Simulated HTTP response for an artifact endpoint."""

    status_code: int
    content_type: str
    body_size: int
    cache_control: Optional[str]


# ---------------------------------------------------------------------------
# Implementation-under-test: Health check retry logic
# ---------------------------------------------------------------------------

# Constants matching the ComfyUI client implementation
MAX_RETRIES = 3
BACKOFF_DELAYS = [2.0, 4.0, 8.0]
INITIAL_TIMEOUT_S = 5.0
RETRY_TIMEOUT_S = 15.0


def compute_health_check_timing(
    failure_sequence: list[bool],
) -> HealthCheckResult:
    """Simulate health check retry timing given a sequence of pass/fail results.

    The failure_sequence represents whether each attempt fails:
    - failure_sequence[0]: initial attempt
    - failure_sequence[1..3]: retry attempts

    Returns the HealthCheckResult with timing and reporting info.

    This mirrors the logic in ComfyUIClient.health_check().
    """
    total_elapsed = 0.0
    last_error: Optional[str] = None

    # Initial attempt
    if not failure_sequence[0]:
        # Initial attempt succeeded
        return HealthCheckResult(
            success=True,
            attempt_count=1,
            total_elapsed_s=0.0,
            last_error=None,
        )
    last_error = "timeout after initial attempt"

    # Retry attempts with exponential backoff
    for retry_idx in range(min(MAX_RETRIES, len(failure_sequence) - 1)):
        delay = BACKOFF_DELAYS[retry_idx]
        total_elapsed += delay

        attempt_fails = failure_sequence[retry_idx + 1]
        if not attempt_fails:
            # This retry succeeded
            return HealthCheckResult(
                success=True,
                attempt_count=retry_idx + 2,  # 1-indexed: initial + retries
                total_elapsed_s=total_elapsed,
                last_error=None,
            )
        last_error = f"timeout after retry {retry_idx + 1}"

    # All retries exhausted
    return HealthCheckResult(
        success=False,
        attempt_count=1 + MAX_RETRIES,
        total_elapsed_s=total_elapsed,
        last_error=last_error,
    )


# ---------------------------------------------------------------------------
# Implementation-under-test: Image validity checking
# ---------------------------------------------------------------------------


def validate_image_dimensions(width: int, height: int) -> bool:
    """Check if image dimensions meet the minimum 512x512 requirement."""
    return width >= 512 and height >= 512


def is_valid_png(data: bytes) -> bool:
    """Check if data is a valid PNG by verifying the magic bytes and IHDR chunk."""
    PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
    if len(data) < 24:
        return False
    if data[:8] != PNG_MAGIC:
        return False
    # IHDR chunk should follow the magic bytes
    # Bytes 8-11: chunk length (should be 13 for IHDR)
    # Bytes 12-15: chunk type (should be "IHDR")
    chunk_type = data[12:16]
    return chunk_type == b"IHDR"


def is_valid_jpeg(data: bytes) -> bool:
    """Check if data is a valid JPEG by verifying SOI and APP0/APP1 markers."""
    if len(data) < 4:
        return False
    # JPEG starts with SOI marker: 0xFF 0xD8
    if data[0:2] != b"\xff\xd8":
        return False
    # Next marker should be APP0 (0xFF 0xE0) or APP1 (0xFF 0xE1) or other valid markers
    if data[2] != 0xFF:
        return False
    return True


def validate_generated_image(data: bytes, width: int, height: int) -> tuple[bool, str]:
    """Validate a generated image meets requirements.

    Returns (valid, reason) tuple.
    Requirements: dimensions >= 512x512, valid PNG or JPEG encoding.
    """
    if not validate_image_dimensions(width, height):
        return False, f"Dimensions {width}x{height} below minimum 512x512"

    if is_valid_png(data) or is_valid_jpeg(data):
        return True, "Valid image"

    return False, "Not valid PNG or JPEG encoding"


# ---------------------------------------------------------------------------
# Implementation-under-test: Artifact endpoint correctness
# ---------------------------------------------------------------------------

VALID_CONTENT_TYPES = frozenset(["image/png", "image/jpeg"])
MIN_ARTIFACT_SIZE = 1024  # 1KB minimum


def validate_artifact_response(response: ArtifactResponse) -> tuple[bool, list[str]]:
    """Validate an artifact endpoint response meets all requirements.

    Checks:
    - HTTP 200 status
    - Content-Type is image/png or image/jpeg
    - Body size > 1KB
    - Cache-Control: no-store header present

    Returns (valid, list_of_failures).
    """
    failures: list[str] = []

    if response.status_code != 200:
        failures.append(f"Expected HTTP 200, got {response.status_code}")

    if response.content_type not in VALID_CONTENT_TYPES:
        failures.append(
            f"Expected Content-Type in {sorted(VALID_CONTENT_TYPES)}, "
            f"got '{response.content_type}'"
        )

    if response.body_size <= MIN_ARTIFACT_SIZE:
        failures.append(
            f"Expected body size > {MIN_ARTIFACT_SIZE} bytes, "
            f"got {response.body_size}"
        )

    if response.cache_control is None or "no-store" not in response.cache_control:
        failures.append(
            f"Expected Cache-Control containing 'no-store', "
            f"got '{response.cache_control}'"
        )

    return (len(failures) == 0, failures)


