class TestProperty15GeneratedImageValidity:
    """**Validates: Requirements 18.3**

    For any image generated by the FLUX pipeline via ComfyUI, the output SHALL
    have dimensions of at least 512x512 pixels and valid PNG or JPEG encoding
    (parseable by standard image libraries without error).
    """

    @given(
        width=_valid_dimension_st,
        height=_valid_dimension_st,
    )
    @_SETTINGS
    def test_valid_dimensions_pass(self, width: int, height: int) -> None:
        """Images with dimensions >= 512x512 pass the dimension check.

        **Validates: Requirements 18.3**
        """
        assert validate_image_dimensions(width, height) is True, (
            f"Dimensions {width}x{height} should pass (>= 512x512)"
        )

    @given(
        width=_invalid_dimension_st,
        height=_dimension_st,
    )
    @_SETTINGS
    def test_invalid_width_fails(self, width: int, height: int) -> None:
        """Images with width < 512 fail the dimension check.

        **Validates: Requirements 18.3**
        """
        assert validate_image_dimensions(width, height) is False, (
            f"Width {width} < 512 should fail"
        )

    @given(
        width=_dimension_st,
        height=_invalid_dimension_st,
    )
    @_SETTINGS
    def test_invalid_height_fails(self, width: int, height: int) -> None:
        """Images with height < 512 fail the dimension check.

        **Validates: Requirements 18.3**
        """
        assert validate_image_dimensions(width, height) is False, (
            f"Height {height} < 512 should fail"
        )

    @given(
        width=_valid_dimension_st,
        height=_valid_dimension_st,
    )
    @_SETTINGS
    def test_valid_png_with_valid_dimensions_passes(
        self, width: int, height: int
    ) -> None:
        """Valid PNG encoding + valid dimensions = overall pass.

        **Validates: Requirements 18.3**
        """
        png_data = _make_png_bytes(width, height)
        valid, reason = validate_generated_image(png_data, width, height)
        assert valid is True, f"Valid PNG with {width}x{height} should pass: {reason}"

    @given(
        width=_valid_dimension_st,
        height=_valid_dimension_st,
    )
    @_SETTINGS
    def test_valid_jpeg_with_valid_dimensions_passes(
        self, width: int, height: int
    ) -> None:
        """Valid JPEG encoding + valid dimensions = overall pass.

        **Validates: Requirements 18.3**
        """
        jpeg_data = _make_jpeg_bytes(2048)
        valid, reason = validate_generated_image(jpeg_data, width, height)
        assert valid is True, f"Valid JPEG with {width}x{height} should pass: {reason}"

    @given(
        width=_valid_dimension_st,
        height=_valid_dimension_st,
        random_bytes=st.binary(min_size=100, max_size=1000),
    )
    @_SETTINGS
    def test_invalid_encoding_fails(
        self, width: int, height: int, random_bytes: bytes
    ) -> None:
        """Random bytes that are neither PNG nor JPEG fail validation.

        **Validates: Requirements 18.3**
        """
        # Ensure the random bytes don't accidentally look like PNG or JPEG
        assume(not random_bytes.startswith(b"\x89PNG\r\n\x1a\n"))
        assume(not random_bytes.startswith(b"\xff\xd8\xff"))

        valid, reason = validate_generated_image(random_bytes, width, height)
        assert valid is False, (
            f"Random bytes should not pass as valid image: {reason}"
        )
        assert "encoding" in reason.lower() or "not valid" in reason.lower()

    @given(
        width=_invalid_dimension_st,
        height=_invalid_dimension_st,
    )
    @_SETTINGS
    def test_invalid_dimensions_fail_regardless_of_encoding(
        self, width: int, height: int
    ) -> None:
        """Even with valid PNG encoding, undersized dimensions fail.

        **Validates: Requirements 18.3**
        """
        png_data = _make_png_bytes(width, height)
        valid, reason = validate_generated_image(png_data, width, height)
        assert valid is False, (
            f"Dimensions {width}x{height} should fail even with valid PNG"
        )
        assert "512" in reason, f"Failure reason should mention 512: {reason}"


