"""Property-based tests for GPU infrastructure: health check retry, image validity, artifacts.

Tests three correctness properties specified in the design document:

Property 14: Health Check Retry Timing
    For any health check failure sequence, retries SHALL follow exponential
    backoff with delays of 2s, 4s, and 8s (3 retries maximum), and the failure
    report SHALL include attempt count, total elapsed time, and last error received.

Property 15: Generated Image Validity
    For any image generated by the FLUX pipeline via ComfyUI, the output SHALL
    have dimensions of at least 512x512 pixels and valid PNG or JPEG encoding
    (parseable by standard image libraries without error).

Property 16: Artifact Endpoint Correctness
    For any completed stage artifact served via API, the response SHALL have
    HTTP 200, correct Content-Type (image/png or image/jpeg), file size > 1KB,
    and Cache-Control: no-store header.

**Validates: Requirements 17.1, 17.3, 18.3, 19.1, 19.3, 19.4**

Testing framework: Hypothesis (as specified in design document)
"""
from __future__ import annotations

import io
