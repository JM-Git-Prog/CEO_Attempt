# ---------------------------------------------------------------------------
# Helper: Generate minimal valid PNG bytes
# ---------------------------------------------------------------------------


def _make_png_bytes(width: int, height: int) -> bytes:
    """Generate minimal valid PNG bytes with given dimensions."""
    # PNG magic + IHDR chunk
    magic = b"\x89PNG\r\n\x1a\n"
    # IHDR: 4 bytes width, 4 bytes height, 1 bit depth, 1 color type,
    # 1 compression, 1 filter, 1 interlace = 13 bytes
    ihdr_data = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    ihdr_length = struct.pack(">I", 13)
    ihdr_type = b"IHDR"
    # CRC placeholder (not validated in our check)
    ihdr_crc = b"\x00\x00\x00\x00"
    return magic + ihdr_length + ihdr_type + ihdr_data + ihdr_crc


def _make_jpeg_bytes(size: int = 2048) -> bytes:
    """Generate minimal valid JPEG bytes."""
    # SOI + APP0 marker + padding
    soi = b"\xff\xd8"
    app0_marker = b"\xff\xe0"
    # Fill to requested size
    padding = b"\x00" * max(0, size - 4)
    return soi + app0_marker + padding


# ---------------------------------------------------------------------------
# Property 14: Health Check Retry Timing
# ---------------------------------------------------------------------------


class TestProperty14HealthCheckRetryTiming:
    """**Validates: Requirements 17.1, 17.3**

    For any health check failure sequence, retries SHALL follow exponential
    backoff with delays of 2s, 4s, and 8s (3 retries maximum), and the failure
    report SHALL include attempt count, total elapsed time, and last error received.
    """

    @given(failure_sequence=_failure_sequence_st)
    @_SETTINGS
    def test_max_attempts_is_four(self, failure_sequence: list[bool]) -> None:
        """Total attempts never exceed 1 initial + 3 retries = 4.

        **Validates: Requirements 17.1**
        """
        result = compute_health_check_timing(failure_sequence)
        assert result.attempt_count <= 1 + MAX_RETRIES, (
            f"Attempt count {result.attempt_count} exceeds maximum "
            f"{1 + MAX_RETRIES} for sequence {failure_sequence}"
        )

    @given(failure_sequence=_failure_sequence_st)
    @_SETTINGS
    def test_backoff_timing_is_exponential(
        self, failure_sequence: list[bool]
    ) -> None:
        """Total elapsed time follows 2s + 4s + 8s = 14s max cumulative backoff.

        **Validates: Requirements 17.1**
        """
        result = compute_health_check_timing(failure_sequence)

        # Maximum total backoff delay is sum of all delays: 2 + 4 + 8 = 14
        max_total_backoff = sum(BACKOFF_DELAYS)
        assert result.total_elapsed_s <= max_total_backoff, (
            f"Total elapsed {result.total_elapsed_s:.1f}s exceeds max "
            f"backoff {max_total_backoff:.1f}s"
        )

    @given(failure_sequence=st.lists(st.just(True), min_size=4, max_size=4))
    @_SETTINGS
    def test_all_failures_report_correctly(
        self, failure_sequence: list[bool]
    ) -> None:
        """When all attempts fail, report includes attempt count, elapsed time, and last error.

        **Validates: Requirements 17.3**
        """
        result = compute_health_check_timing(failure_sequence)

        # All failed
        assert result.success is False
        # Total attempts = 1 initial + 3 retries
        assert result.attempt_count == 4
        # Total elapsed = 2 + 4 + 8 = 14s
        assert result.total_elapsed_s == sum(BACKOFF_DELAYS)
        # Last error is reported
        assert result.last_error is not None
        assert len(result.last_error) > 0

    @given(
        num_failures_before_success=st.integers(min_value=0, max_value=3),
    )
    @_SETTINGS
    def test_success_after_n_failures_reports_correct_timing(
        self, num_failures_before_success: int
    ) -> None:
        """When health check succeeds after N failures, timing matches expected backoff.

        **Validates: Requirements 17.1, 17.3**
        """
        # Build a sequence: N failures then 1 success
        failure_sequence = [True] * num_failures_before_success + [False]
        # Pad to max length to ensure we don't go out of bounds
        failure_sequence = failure_sequence + [True] * (4 - len(failure_sequence))

        result = compute_health_check_timing(failure_sequence)

        assert result.success is True
        assert result.attempt_count == num_failures_before_success + 1

        # Expected elapsed: sum of backoff delays for the failures
        # (first failure = initial attempt, no backoff before it)
        if num_failures_before_success == 0:
            expected_elapsed = 0.0
        else:
            expected_elapsed = sum(BACKOFF_DELAYS[:num_failures_before_success])

        assert abs(result.total_elapsed_s - expected_elapsed) < 0.001, (
            f"Expected elapsed {expected_elapsed:.1f}s after "
            f"{num_failures_before_success} failures, got {result.total_elapsed_s:.1f}s"
        )

    @given(failure_sequence=_failure_sequence_st)
    @_SETTINGS
    def test_backoff_delays_are_2_4_8(
        self, failure_sequence: list[bool]
    ) -> None:
        """Exponential backoff delays are exactly 2s, 4s, 8s.

        **Validates: Requirements 17.1**
        """
        # Verify the constants match the spec
        assert BACKOFF_DELAYS == [2.0, 4.0, 8.0], (
            f"Backoff delays {BACKOFF_DELAYS} don't match spec [2, 4, 8]"
        )
        # And max retries is exactly 3
        assert MAX_RETRIES == 3


